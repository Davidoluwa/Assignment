bool plx_font_pixel(char ch, int col, int row) {
    unsigned char c = (unsigned char)ch;
    if (c < 32 || c > 126) c = '?';
    if (col < 0 || col >= PLX_FONT_W || row < 0 || row >= PLX_FONT_H) return false;
    return font[c - 32][row][col] == '#';
}

void plx_text_size(const char *s, int scale, int *w, int *h) {
    int lines = 1, len = 0, maxlen = 0;
    for (; *s; s++) {
        if (*s == '\n') { lines++; len = 0; continue; }
        maxlen = PLX_MAX(maxlen, ++len);
    }
    /* The last glyph's trailing spacing column and the last line gap are not counted. */
    *w = maxlen ? (maxlen * PLX_FONT_ADV - 1) * scale : 0;
    *h = (lines * PLX_FONT_LINE - 1) * scale;
}

void plx_draw_text(plx_img *im, int x, int y, const char *s, int scale, const float rgb[3]) {
    PLX_ASSERT(im->c == 3 && scale >= 1);
    size_t plane = (size_t)im->w * im->h;
    int cx = x, cy = y;
    for (; *s; s++) {
        if (*s == '\n') { cx = x; cy += PLX_FONT_LINE * scale; continue; }
        for (int r = 0; r < PLX_FONT_H; r++)
            for (int c = 0; c < PLX_FONT_W; c++) {
                if (!plx_font_pixel(*s, c, r)) continue;
                for (int dy = 0; dy < scale; dy++) {
                    int py = cy + r * scale + dy;
                    if (py < 0 || py >= im->h) continue;
                    for (int dx = 0; dx < scale; dx++) {
                        int px = cx + c * scale + dx;
                        if (px < 0 || px >= im->w) continue;
                        size_t i = (size_t)py * im->w + px;
                        for (int k = 0; k < 3; k++) im->px[k * plane + i] = rgb[k];
                    }
                }
            }
        cx += PLX_FONT_ADV * scale;
    }
}
